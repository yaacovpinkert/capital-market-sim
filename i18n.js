let lang = 'en';
try {
  const saved = localStorage.getItem(LANG_KEY);
  if (saved === 'he' || saved === 'en') lang = saved;
  else if (typeof navigator !== 'undefined' && /^he/i.test(navigator.language || '')) lang = 'he';
} catch (e) { /* ignore */ }

const HEB = /[֐-׿]/;
// In Hebrew, wrap Latin/number tokens in a left-to-right isolate so they keep their order inside RTL sentences
const isolate = v => (lang === 'he' && !HEB.test(v) ? '⁦' + v + '⁩' : v);

function t(key, params) {
  let s = (I18N[lang] && I18N[lang][key]) ?? I18N.en[key] ?? key;
  if (params) s = s.replace(/\{(\w+)\}/g, (m, k) => (k in params ? isolate(String(params[k])) : m));
  return s;
}

const locale = () => (lang === 'he' ? 'he-IL' : 'en-US');
const nameOf = s => (lang === 'he' && NAMES_HE[s.sym]) || s.name;

function applyI18n() {
  document.documentElement.lang = lang;
  document.documentElement.dir = lang === 'he' ? 'rtl' : 'ltr';
  document.title = t('title');
  document.querySelectorAll('[data-i18n]').forEach(el => { el.textContent = t(el.dataset.i18n); });
  document.querySelectorAll('[data-i18n-html]').forEach(el => { el.innerHTML = t(el.dataset.i18nHtml); });
  document.querySelectorAll('[data-i18n-ph]').forEach(el => { el.placeholder = t(el.dataset.i18nPh); });
  document.querySelectorAll('[data-i18n-title]').forEach(el => { el.title = t(el.dataset.i18nTitle); });
}

function setLang(l) {
  lang = l === 'he' ? 'he' : 'en';
  try { localStorage.setItem(LANG_KEY, lang); } catch (e) { /* ignore */ }
  applyI18n();
  if (typeof onLangChange === 'function') onLangChange();
}
